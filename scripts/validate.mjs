#!/usr/bin/env node
// Validate every template in the repository.
//
//   node scripts/validate.mjs              # all templates + templates.json
//   node scripts/validate.mjs <file...>    # specific files
//   node scripts/validate.mjs --fix-hand   # write the quality verdict into hand-authored templates
//
// Checks each file against data/template.schema.json (ajv, draft 2020-12),
// the shape cdecli `workflow create-from-json` and the editor's Import expect,
// that every edge names a socket the node really has, that every connector
// action exists in data/connector-actions.json, that template.tier /
// blockers / setup match what lib/quality.mjs computes, and the repository
// conventions (slug == file name, one Workflow Configs node, an entry node,
// no em dashes in generated text). templates.json is checked against
// data/templates.schema.json.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { NODE_TYPES, socketsCompatible, ENTRY_TYPES } from './lib/yantra-nodes.mjs';
import { ROOT, listTemplates, loadCatalog, loadVerified, STATUSES } from './lib/catalog-fs.mjs';
import { evaluate } from './lib/quality.mjs';
import { validateChainSchema } from './lib/llm-chain.mjs';
import { validateItemLoops } from './lib/item-loops.mjs';
import { validateRepeatLoops } from './lib/repeat-loops.mjs';

/**
 * Every NodeTransform body is compiled the way the editor runs it
 * (`new Function('source', code)` after `{{...}}` tokens are resolved) and then
 * executed once against an empty payload. A syntax error, or a ReferenceError
 * for an identifier the generated shims should have defined, is a defect in
 * the template; data errors (reading a field of undefined) are not, because
 * the payload is fake.
 */
function checkJsCode(code) {
  const resolved = code.replace(/\{\{\{?\s*([\w$][\w$.[\]-]*)\s*\}?\}\}/g, (_m, p) => (p === 'ctx' ? '{"body":{},"steps":{},"last":null}' : 'null'));
  // Host globals the editor's runtime (browser or Node) provides on top of the JS builtins.
  const host = { TextEncoder, TextDecoder, atob, btoa, URL, URLSearchParams, console: { log() {}, warn() {}, error() {} }, structuredClone, setTimeout: () => 0, crypto: globalThis.crypto };
  let fn;
  try {
    fn = vm.runInNewContext(`(function (source) {\n"use strict";\n${resolved}\n})`, host, { timeout: 1000 });
  } catch (e) {
    return `jsCode does not compile: ${e.message}`;
  }
  for (const source of [{}, [{ a: 1 }], 'text']) {
    try {
      fn(source);
    } catch (e) {
      if (e instanceof ReferenceError || /is not defined/.test(String(e.message))) return `jsCode references an undefined identifier: ${e.message}`;
    }
  }
  return null;
}

const root = ROOT;
const catalog = loadCatalog();
const verified = loadVerified();
const indexPath = path.join(root, 'templates.json');
const index = fs.existsSync(indexPath) ? JSON.parse(fs.readFileSync(indexPath, 'utf8')) : null;
const argv = process.argv.slice(2);
const FIX_HAND = argv.includes('--fix-hand');
const fileArgs = argv.filter((a) => !a.startsWith('--'));

// JSON Schema (draft 2020-12) validation with ajv.
let Ajv2020;
try {
  ({ default: Ajv2020 } = await import('ajv/dist/2020.js'));
} catch {
  console.error('ajv is not installed; run `npm ci` first');
  process.exit(2);
}
const ajv = new Ajv2020({ allErrors: true, strict: false });
const validateTemplateSchema = ajv.compile(JSON.parse(fs.readFileSync(path.join(root, 'data', 'template.schema.json'), 'utf8')));
const validateIndexSchema = ajv.compile(JSON.parse(fs.readFileSync(path.join(root, 'data', 'templates.schema.json'), 'utf8')));
const schemaErrors = (errors) => (errors || []).slice(0, 8).map((e) => `schema: ${e.instancePath || '/'} ${e.message}${e.params?.allowedValues ? ` (${e.params.allowedValues.join(', ')})` : ''}`);

/**
 * Hand-authored templates are not regenerated by the converter, so their
 * quality verdict is written here: `node scripts/validate.mjs --fix-hand`.
 * Older hand files keep their prose setup list as conversion.hints.
 */
function fixHand(rel) {
  const file = path.join(root, rel);
  const wf = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (wf.template?.conversion?.tool !== 'hand') return false;
  const t = wf.template;
  if (t.schemaVersion !== 2) {
    t.schemaVersion = 2;
    if (!t.conversion.hints) t.conversion.hints = Array.isArray(t.setup) ? t.setup : [];
    t.conversion.triggers ||= [];
  }
  const q = evaluate(wf, { catalog, verified, path: rel });
  t.conversion.status = q.status;
  const ordered = {};
  for (const [k, v] of Object.entries(t)) {
    if (['tier', 'blockers', 'setup'].includes(k)) continue;
    if (k === 'conversion') Object.assign(ordered, { tier: q.tier, blockers: q.blockers, setup: q.setup });
    ordered[k] = v;
  }
  wf.template = ordered;
  const text = JSON.stringify(wf, null, 2) + '\n';
  if (text === fs.readFileSync(file, 'utf8')) return false;
  fs.writeFileSync(file, text);
  return true;
}

const ID_RE = /^(node|actor)_[a-z0-9]{6,}$/;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function validateTemplate(rel) {
  const errors = [];
  const err = (m) => errors.push(m);
  let wf;
  try {
    wf = JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));
  } catch (e) {
    return [`invalid JSON: ${e.message}`];
  }

  if (!validateTemplateSchema(wf)) errors.push(...schemaErrors(validateTemplateSchema.errors));
  const file = path.basename(rel, '.json');
  const category = path.dirname(rel);
  if (typeof wf.name !== 'string' || !wf.name.trim()) err('name is required');
  if (wf.workflowSlug !== file) err(`workflowSlug "${wf.workflowSlug}" must equal the file name "${file}"`);
  if (!SLUG_RE.test(String(wf.workflowSlug))) err('workflowSlug must be kebab-case');
  if (typeof wf.description !== 'string') err('description must be a string');
  if (typeof wf.isPublic !== 'boolean') err('isPublic must be a boolean');
  if (!Array.isArray(wf.nodes) || wf.nodes.length === 0) err('nodes must be a non-empty array');
  if (!Array.isArray(wf.edges)) err('edges must be an array');
  if (!wf.template || typeof wf.template !== 'object') err('template metadata block is required');
  else {
    if (wf.template.category !== category) err(`template.category "${wf.template.category}" must equal the folder "${category}"`);
    if (!wf.template.source?.path && wf.template.conversion?.tool !== 'hand') err('template.source.path is required');
    if (!STATUSES.includes(wf.template.conversion?.status)) err(`template.conversion.status must be ${STATUSES.join(' | ')}`);
    if (!['scripts/convert-n8n.mjs', 'hand'].includes(wf.template.conversion?.tool)) err('template.conversion.tool must be scripts/convert-n8n.mjs or hand');
    const cmp = wf.template.comparison;
    if (!cmp || typeof cmp.n8nSteps !== 'number' || typeof cmp.yantraSteps !== 'number') err('template.comparison.n8nSteps and yantraSteps are required');
  }
  if (errors.length) return errors;

  const byId = new Map();
  let configs = 0;
  let entries = 0;
  for (const [i, n] of wf.nodes.entries()) {
    const where = `nodes[${i}] (${n.nodeId ?? '?'})`;
    const spec = NODE_TYPES[n.type];
    if (!spec) err(`${where}: unknown node type "${n.type}"`);
    for (const k of ['nodeId', 'actorId', 'type', 'label', 'color']) if (typeof n[k] !== 'string' || !n[k]) err(`${where}: ${k} is required`);
    if (!ID_RE.test(n.nodeId ?? '') || !ID_RE.test(n.actorId ?? '')) err(`${where}: nodeId/actorId must look like node_<hash> / actor_<hash>`);
    if (n.nodeId && n.actorId && n.nodeId.slice(5) !== n.actorId.slice(6)) err(`${where}: nodeId and actorId must share the same hash`);
    if (byId.has(n.nodeId)) err(`${where}: duplicate nodeId`);
    byId.set(n.nodeId, n);
    if (typeof n.position?.x !== 'number' || typeof n.position?.y !== 'number') err(`${where}: position {x,y} is required`);
    if (typeof n.size?.width !== 'number' || typeof n.size?.height !== 'number') err(`${where}: size {width,height} is required`);
    if (n.inputs !== undefined && (typeof n.inputs !== 'object' || Array.isArray(n.inputs))) err(`${where}: inputs must be an object`);
    if (spec && n.inputs) {
      for (const k of Object.keys(n.inputs)) {
        if (n.type === 'NodeCdeConnector' && ['connectorName', 'connectorLabel', 'connectorActions'].includes(k)) continue;
        if (!spec.inputs[k]) err(`${where}: input "${k}" is not a socket of ${n.type}`);
      }
    }
    if (n.type === 'NodeWorkflowConfigs') configs += 1;
    if (n.type === 'NodeChatModel') {
      if (typeof n.inputs?.provider !== 'string' || !n.inputs.provider.trim()) err(`${where}: Chat Model needs a provider`);
      if (typeof n.inputs?.model !== 'string' || !n.inputs.model.trim()) err(`${where}: Chat Model needs a model ID or declared setup token`);
      if (!wf.template.connectors.includes(n.inputs?.provider)) err(`${where}: Chat Model provider must be in template.connectors`);
    }
    if (n.type === 'NodeLlmChain') {
      const models = wf.edges.filter((e) => e.target === n.nodeId && e.targetInput === 'llm');
      if (models.length !== 1 || models[0].sourceOutput !== 'config' || !wf.nodes.some((m) => m.nodeId === models[0].source && m.type === 'NodeChatModel')) err(`${where}: connect one Chat Model config output to llm`);
      if (!n.inputs?.prompt?.trim?.() && !wf.edges.some((e) => e.target === n.nodeId && e.targetInput === 'prompt')) err(`${where}: LLMChain needs a prompt or incoming prompt edge`);
      if (!['text', 'structured'].includes(n.inputs?.outputMode)) err(`${where}: LLMChain outputMode must be text | structured`);
      if (n.inputs?.outputMode === 'structured') {
        if (!['prompt', 'native'].includes(n.inputs.schemaMode)) err(`${where}: LLMChain schemaMode must be prompt | native`);
        try { validateChainSchema(n.inputs.schema); } catch (e) { err(`${where}: ${e.message}`); }
      }
    }
    if (ENTRY_TYPES.has(n.type)) entries += 1;
    if (n.type === 'NodeCdeConnector') {
      const c = n.inputs?.connectorName;
      const a = n.inputs?.action;
      if (!c) err(`${where}: connectorName is required`);
      if (!a) err(`${where}: action is required`);
      if (n.label !== `${c}/${a}`) err(`${where}: label must be "${c}/${a}"`);
      const known = catalog.connectors[c];
      if (!known) err(`${where}: connector "${c}" is not in data/connector-actions.json`);
      else if (a && !known.actions[a]) err(`${where}: action "${a}" is not an action of connector "${c}" (see npm run catalog -- --check)`);
      if (n.inputs?.params !== undefined && (typeof n.inputs.params !== 'object' || Array.isArray(n.inputs.params))) err(`${where}: params must be an object`);
    }
    if (n.type === 'NodeCdeWebhookTrigger') {
      const c = n.inputs?.connector;
      const slug = n.inputs?.triggerSlug;
      const known = catalog.connectors[c];
      if (!known) err(`${where}: webhook connector "${c}" is not in data/connector-actions.json`);
      else if (!known.triggers?.includes(slug)) err(`${where}: trigger slug "${slug}" is not a trigger of "${c}"`);
    }
    if (n.type === 'NodeTransform') {
      if (typeof n.inputs?.jsCode !== 'string' || !n.inputs.jsCode.trim()) err(`${where}: NodeTransform needs inputs.jsCode`);
      else {
        const problem = checkJsCode(n.inputs.jsCode);
        if (problem) err(`${where} "${n.label}": ${problem}`);
      }
      if (!['pick', 'omit', 'jsCode'].includes(n.inputs?.mode)) err(`${where}: NodeTransform mode must be pick | omit | jsCode`);
    }
    if (n.type === 'NodeCron' && !n.inputs?.cronExpression && !n.inputs?.interval) err(`${where}: NodeCron needs cronExpression or interval`);
  }
  if (configs !== 1) err(`exactly one NodeWorkflowConfigs node is required (found ${configs})`);
  if (entries === 0) err('at least one entry node (NodeStart, NodeCron or NodeCdeWebhookTrigger) is required');

  const seen = new Set();
  for (const [i, e] of wf.edges.entries()) {
    const where = `edges[${i}]`;
    const src = byId.get(e.source);
    const dst = byId.get(e.target);
    if (!src) err(`${where}: unknown source node "${e.source}"`);
    if (!dst) err(`${where}: unknown target node "${e.target}"`);
    if (!src || !dst) continue;
    if (e.sourceNodeType !== src.type) err(`${where}: sourceNodeType "${e.sourceNodeType}" does not match ${src.type}`);
    if (e.targetNodeType !== dst.type) err(`${where}: targetNodeType "${e.targetNodeType}" does not match ${dst.type}`);
    const out = NODE_TYPES[src.type]?.outputs[e.sourceOutput];
    const inp = NODE_TYPES[dst.type]?.inputs[e.targetInput];
    if (!out) err(`${where}: ${src.type} has no output socket "${e.sourceOutput}"`);
    if (!inp) err(`${where}: ${dst.type} has no input socket "${e.targetInput}"`);
    if (out && inp) {
      if (!!out.trigger !== !!inp.trigger) err(`${where}: ${e.sourceOutput} -> ${e.targetInput} mixes a trigger socket with a data socket`);
      else if (!out.trigger && !socketsCompatible(out.type, inp.type)) err(`${where}: socket types ${out.type} -> ${inp.type} are not compatible`);
    }
    const key = `${e.source}:${e.sourceOutput}>${e.target}:${e.targetInput}`;
    if (seen.has(key)) err(`${where}: duplicate edge ${key}`);
    seen.add(key);
  }

  const text = JSON.stringify(wf);
  errors.push(...validateItemLoops(wf));
  errors.push(...validateRepeatLoops(wf));
  if (text.includes('—')) err('em dash found; use a plain dash');

  // The quality verdict written in the file must be the one lib/quality.mjs computes now.
  const q = evaluate(wf, { catalog, verified, path: rel });
  const t = wf.template || {};
  if (t.tier !== q.tier) err(`template.tier is "${t.tier}" but the quality gate computes "${q.tier}" (re-run npm run convert${t.conversion?.tool === 'hand' ? ' or validate --fix-hand' : ''})`);
  if (JSON.stringify(t.blockers) !== JSON.stringify(q.blockers)) err('template.blockers are out of date with lib/quality.mjs');
  if (JSON.stringify(t.setup) !== JSON.stringify(q.setup)) err('template.setup is out of date with lib/quality.mjs');
  if (t.conversion?.status !== q.status) err(`template.conversion.status must be "${q.status}" for tier ${q.tier}`);
  if (verified.has(rel) && q.tier !== 'verified') err('listed in data/verified.json but has experimental blockers; re-verify or remove the entry');

  if (index) {
    const row = index.templates.find((x) => x.path === rel);
    if (!row) err('missing from templates.json (run npm run index)');
    else if (row.tier !== q.tier) err(`templates.json lists tier "${row.tier}", expected "${q.tier}" (run npm run index)`);
  }
  return errors;
}

const files = fileArgs.length ? fileArgs.map((f) => path.relative(root, path.resolve(f))) : listTemplates();
if (FIX_HAND) {
  const fixed = files.filter(fixHand);
  console.log(`--fix-hand: rewrote ${fixed.length} hand-authored template(s)${fixed.length ? `: ${fixed.join(', ')}` : ''}`);
}
let failed = 0;
let indexFailed = 0;
for (const rel of files) {
  const errors = validateTemplate(rel);
  if (errors.length) {
    failed += 1;
    console.error(`FAIL ${rel}`);
    for (const e of errors) console.error(`   - ${e}`);
  }
}
if (index && !fileArgs.length) {
  if (!validateIndexSchema(index)) {
    indexFailed += 1;
    console.error('FAIL templates.json');
    for (const e of schemaErrors(validateIndexSchema.errors)) console.error(`   - ${e}`);
  }
  const onDisk = new Set(files);
  for (const t of index.templates) if (!onDisk.has(t.path)) {
    indexFailed += 1;
    console.error(`FAIL templates.json lists a missing file: ${t.path}`);
  }
}
console.log(`${files.length - failed}/${files.length} templates valid${indexFailed ? `; templates.json has ${indexFailed} problem(s)` : ''}`);
process.exit(failed || indexFailed ? 1 : 0);
